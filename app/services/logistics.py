"""logistics.py — 物流承运商信息

小程序端物流模块按产品要求只展示：物流公司名称、运单号、官方查询电话，
不返回任何物流轨迹节点。这里维护常见承运商的官方客服电话映射。

职责：
- 根据用户填写的物流公司名称，匹配官方查询电话，供小程序直接展示。

关键数据流：
  订单物流公司名 → phone_of → _PHONE_RULES 关键词顺序匹配 → 电话 / 空串

依赖：无外部服务，纯本地静态映射。

失败降级策略：
- 未匹配到或名称为空时返回空串，由前端展示缺省文案，不抛异常。

注意事项：
- 关键词匹配使用大写归一化，兼容「EMS/ems」等英文大小写差异；
- 规则顺序敏感（如「邮政」与「EMS」），新增时应避免更短关键词抢占。
"""

# (公司名关键词, 官方查询电话)；按顺序匹配，命中即返回
_PHONE_RULES: list[tuple[str, str]] = [
    ("顺丰", "95338"),
    ("中通", "95311"),
    ("圆通", "95554"),
    ("韵达", "95546"),
    ("申通", "95543"),
    ("京东", "950616"),
    ("邮政", "11183"),
    ("EMS", "11183"),
    ("极兔", "956025"),
    ("德邦", "95353"),
    ("百世", "95320"),
    ("天天", "4001888888"),
    ("宅急送", "4006789000"),
]


def phone_of(company: str | None) -> str:
    """根据物流公司名称返回官方查询电话；未知承运商返回空串（前端展示缺省值）。

    Args:
        company: 物流公司名称，可为 None。

    Returns:
        str: 匹配到的客服电话；未匹配返回空串。
    """
    name = (company or "").strip()
    if not name:
        return ""
    upper = name.upper()
    for keyword, phone in _PHONE_RULES:
        if keyword.upper() in upper:
            return phone
    return ""
